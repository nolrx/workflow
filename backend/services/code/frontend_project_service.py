"""
Frontend PROJECT build service (agentic, container-sandboxed).

Unlike the removed single-file HTML flow (one text-model call returning a single
inline index.html), this drives an autonomous coding CLI (Claude Code, headless) inside
a throwaway Docker container to produce a COMPLETE multi-file React + Vite + TS
project that the agent itself builds and self-checks.

Sandbox properties (validated by PoC):
  * runs as the non-root ``node`` user (the CLI refuses bypassPermissions as root);
  * the only host-visible write is the mounted ``/out`` dir — node_modules and the
    npm cache live only in the container fs and die with ``--rm``;
  * the deliverable copied to /out is source + built ``dist`` ONLY.

This deliberately steps OUTSIDE the capability-routed AI provider abstraction:
the CLI owns its own Anthropic backend, so this is an agent-EXECUTION lane, not a
single ``generate_text`` call. Token usage is reported back via the CLI's terminal
``result`` event so the caller can meter it into the credit system.

TWO agents cooperate inside the one container (mirrors the slicer's Codex setup):
  * Claude Code is the PRIMARY engine — it writes the project and self-checks.
  * When the UI needs REAL raster imagery (instead of emoji / placeholders),
    Claude triggers the bundled ``image-assets`` skill, which shells out to the
    OpenAI Codex CLI; Codex generates each picture with the OpenAI image model
    (``genimage.mjs`` -> gpt-image-2) and writes it into ``src/assets/``. Both the
    skill and the helper are written into the container at startup, so no app
    code is baked into the image. The asset lane is FAIL-SOFT: a missing
    OPENAI_API_KEY or an image error never sinks the build (Claude then falls
    back to CSS/SVG — the prompt forbids emoji either way).
"""
