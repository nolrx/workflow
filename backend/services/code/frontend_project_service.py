class FrontendProjectService:
    """Generate a runnable multi-file frontend project via a sandboxed agent."""

    def __init__(self):
        self.image = os.getenv("FE_AGENT_IMAGE", "fe-agent:latest")
        self.docker = os.getenv("DOCKER_BIN", "docker")
        # Per-phase budgets handed to the in-container `timeout` guards. The
        # self-healing ladder (generate + repair + several builds) can run long,
        # so the host's hard ceiling is the SUM of phases plus margin, NOT a single
        # claude budget. The in-container timeouts are the real per-phase guard;
        # total_timeout only backstops a container that never exits.
        # Set FE_AGENT_TIMEOUT / FE_AGENT_REPAIR_TIMEOUT / FE_AGENT_TOTAL_TIMEOUT to
        # 0 to DISABLE the cap for that phase — the agent then runs to completion
        # instead of being killed (124) and degraded. Only a cooperative cancel or
        # the agent finishing stops the run.
        self.gen_timeout = int(os.getenv("FE_AGENT_TIMEOUT", "720"))
        self.repair_timeout = int(os.getenv("FE_AGENT_REPAIR_TIMEOUT", "300"))
        self.npm_timeout = int(os.getenv("FE_AGENT_NPM_TIMEOUT", "240"))
        self.build_timeout = int(os.getenv("FE_AGENT_BUILD_TIMEOUT", "180"))
        self.total_timeout = int(os.getenv("FE_AGENT_TOTAL_TIMEOUT", "2400"))
        # Asset-generation lane (image-assets skill -> Codex -> image model):
        # per-`gen-assets`-call budget and per-image API budget, both in-container.
        self.codex_timeout = int(os.getenv("FE_CODEX_TIMEOUT", "420"))
        self.genimage_timeout = int(os.getenv("FE_GENIMAGE_TIMEOUT", "180"))
        # Runtime browser-smoke (P1-C): headless load of the built dist to capture
        # console/page errors. Optional — skipped fail-soft when the image has no
        # browser baked in (see backend/docker/fe-agent/Dockerfile).
        self.runtime_timeout = int(os.getenv("FE_RUNTIME_TIMEOUT", "90"))

    # --- prompt assembly -----------------------------------------------------
    def _load_prompt(self, name: str) -> str:
        # Mongo-backed (admin-editable); falls back to the bundled default under
        # PROMPT_DIR when Mongo is unavailable.
        return prompt_store.get(f"code/{name}")

    @staticmethod
    def _fill(template: str, **values: str) -> str:
        out = template
        for key, value in values.items():
            out = out.replace(f"[[{key}]]", value if value is not None else "")
        return out

    def _build_prompt(
        self, fill_vals: dict, edit_mode: bool, base_files: dict,
        change_instruction: str, change_plan: str,
    ) -> str:
        """Pick + fill the generation prompt (edit-mode variant for 二次开发续改)."""
        if not edit_mode:
            return self._fill(self._load_prompt("frontend_project_prompt.txt"), **fill_vals)
        base_list = "\n".join(f"- {p}" for p in sorted(base_files)[:300])
        edit_vals = dict(
            fill_vals,
            CHANGE_INSTRUCTION=(change_instruction or "")[:4_000],
            CHANGE_PLAN=(change_plan or "")[:4_000],
            BASE_FILES=base_list,
        )
        try:
            return self._fill(self._load_prompt("frontend_project_edit_prompt.txt"), **edit_vals)
        except Exception:  # noqa: BLE001 — edit template missing: prepend a续改 preamble
            base = self._fill(self._load_prompt("frontend_project_prompt.txt"), **fill_vals)
            return (
                "【二次开发·基于现有项目续改】当前目录已是现有前端工程,请只针对下述变更"
                "修改/新增相关页面、组件、路由与 API 调用,保持其余文件不变,不要整体重写。\n"
                f"变更要求:{(change_instruction or '')[:4000]}\n执行计划:\n{(change_plan or '')[:4000]}\n\n"
                + base
            )

    @staticmethod
    def _seed_base(base_dir: "Path", files: dict) -> None:
        """Write the existing project source under workdir/_base (binary-safe).

        Hardened against path traversal: a crafted zip member name like ``../../x``
        must not escape ``base_dir`` and write onto the host. Absolute paths, ``..``
        segments, and anything that resolves outside base_dir are skipped.
        """
        base_resolved = base_dir.resolve()
        written = 0
        for rel, content in files.items():
            if written > 4000:
                break
            norm = str(rel).replace("\\", "/")
            if not norm or norm.startswith("/") or ".." in norm.split("/"):
                continue
            try:
                dest = base_dir / norm
                resolved = dest.resolve()
                if base_resolved != resolved and base_resolved not in resolved.parents:
                    continue  # escaped base_dir → skip
                dest.parent.mkdir(parents=True, exist_ok=True)
                data = content if isinstance(content, (bytes, bytearray)) else str(content).encode("utf-8")
                dest.write_bytes(bytes(data))
                written += 1
            except Exception:  # noqa: BLE001
                continue

    @staticmethod
    def _extract_json(text: str) -> Optional[dict]:
        """Tolerant single-object JSON parse (code-fence / prefix tolerant)."""
        if not text:
            return None
        cleaned = text.strip()
        fenced = re.search(r"```(?:json)?\s*(.*?)```", cleaned, re.DOTALL | re.IGNORECASE)
        if fenced:
            cleaned = fenced.group(1).strip()
        if not cleaned.startswith("{"):
            match = re.search(r"(\{.*\})", cleaned, re.DOTALL)
            if match:
                cleaned = match.group(1)
        try:
            value = json.loads(cleaned)
            return value if isinstance(value, dict) else None
        except json.JSONDecodeError:
            logger.warning("project review: failed to parse model JSON output")
            return None

    def review_project(
        self,
        *,
        source_digest: str,
        requirements_registry: str,
        style_prompt: str = "",
        features_block: str = "",
        house_rules_report: str = "",
        runtime_report: str = "",
        extra_directive: str = "",
        on_model_call=None,
    ) -> Optional[dict]:
        """Skeptical, rubric-graded acceptance review of the generated project.

        One text-model call (on the reliable text lane) returns a structured
        verdict ``{verdict, scores, fr_coverage, feature_results, blocking_issues,
        advisory_issues, issues, summary}``. The evaluator is fed the deterministic
        signals (``house_rules_report`` / ``runtime_report``) + the acceptance
        ``features_block`` so its judgment is grounded, and its ``blocking_issues``
        drive the verify->repair loop. Returns ``None`` when no text provider is
        configured or on any failure (never raises).
        """
        from backend.services.ai import get_text_provider

        provider = get_text_provider()
        if not provider or not provider.is_configured():
            return None
        prompt = self._fill(
            self._load_prompt("frontend_project_critic_prompt.txt"),
            REQUIREMENTS=requirements_registry or "",
            STYLE_PROMPT=style_prompt or "",
            SOURCE=source_digest or "",
            FEATURES=features_block or "(本次未提供功能清单)",
            HOUSE_RULES=house_rules_report or "(确定性房规检查未发现问题)",
            RUNTIME=runtime_report or "(本次未运行运行时冒烟)",
        )
        if extra_directive:
            prompt += (
                "\n\n# 本次审查侧重(在完成完整 rubric 的同时,尤其严格审查以下方面)\n"
                + extra_directive
            )
        provider_name = getattr(provider, "provider_name", None)
        model_name = getattr(provider, "model", None)
        try:
            result = provider.generate_text(prompt)
        except Exception as error:  # noqa: BLE001 — advisory, never fatal
            logger.warning("project review model call raised: %s", error)
            if on_model_call:
                on_model_call(prompt=prompt, text=None, success=False, error=str(error),
                              provider=provider_name, model=model_name)
            return None
        if on_model_call:
            on_model_call(
                prompt=prompt, text=result.text if result.success else None,
                success=result.success, error=result.error,
                provider=provider_name, model=model_name,
            )
        if not result.success:
            return None
        return self._extract_json(result.text)

    def is_configured(self) -> bool:
        return anthropic_configured()

    def assets_enabled(self) -> bool:
        """Whether the image-assets skill (Codex -> OpenAI image model) can run.

        Independent of ``is_configured`` (which gates the primary Claude engine):
        with no OPENAI_API_KEY the build still succeeds, it just produces no
        generated raster assets (the agent falls back to CSS/SVG)."""
        return bool(os.getenv("OPENAI_API_KEY"))

    # --- public API ----------------------------------------------------------
    # Total budget for the Figma design block injected into the prompt. Visual
    # detail comes from the rendered images (the agent Reads them on demand), so
    # the prompt only carries a compact per-frame IR summary — keeping it bounded
    # even when a whole file has many frames.
    _FIGMA_BLOCK_BUDGET = 18_000

    def _figma_design_block(
        self, frames: Optional[list]
    ) -> tuple[str, list[tuple[str, str]]]:
        """Build the [[FIGMA_DESIGN]] prompt text + the (dest, src) render copies.

        ``frames`` items: ``{name, ir_text, render_path}``. Each frame becomes one
        page/route; its render is referenced as ``design/<dest>.png`` (mounted at
        ``/out/design/<dest>.png`` in the container) for the agent to ``Read``.
        """
        if not frames:
            return "", []
        head = [
            "# Figma 设计稿(视觉真值 — 优先级高于上面的文字风格 / UI 基调)",
            f"本产品有 {len(frames)} 个画板,每个画板对应一个页面/路由。",
            "实现每个页面前,先用 Read 工具读取它的设计图(在 design/ 目录下)作为视觉真值,"
            "精确还原布局、配色、字号、间距与层级;下方 IR 给出精确数值(hex/字号/间距)。",
            "设计稿与文字风格/UI 基调冲突时,以设计稿为准。",
        ]
        sections: list[str] = []
        copies: list[tuple[str, str]] = []
        used = 0
        for index, frame in enumerate(frames):
            name = frame.get("name") or f"frame{index + 1}"
            safe = secure_filename(name) or f"frame{index + 1}"
            dest = f"{index + 1:02d}-{safe}.png"
            src = frame.get("render_path")
            has_img = bool(src and Path(src).exists())
            if has_img:
                copies.append((dest, str(src)))
            ir = (frame.get("ir_text") or "").strip()
            ir = ir[: max(0, self._FIGMA_BLOCK_BUDGET - used)]
            used += len(ir)
            part = [f"\n## 画板 {index + 1}:{name}"]
            part.append(
                f"设计图: design/{dest}(用 Read 工具查看)" if has_img else "(无渲染图,仅依据下方 IR)"
            )
            if ir:
                part.append(f"设计 IR:\n{ir}")
            sections.append("\n".join(part))
        return "\n".join(head) + "\n" + "\n".join(sections), copies

    def build_project(
        self,
        *,
        requirement: str,
        requirements_doc: str = "",
        development_flow: str = "",
        documents_digest: str = "",
        style_prompt: str = "",
        ui_baseline_prompt: str = "",
        context_ledger: str = "",
        contract_block: str = "",
        figma_frames: Optional[list] = None,
        base_files: Optional[dict] = None,
        change_instruction: str = "",
        change_plan: str = "",
        on_event: Optional[Callable[[dict], None]] = None,
        is_cancelled: Optional[Callable[[], bool]] = None,
    ) -> dict:
        """Run the containerized agent through its self-healing build ladder.

        ``base_files`` (二次开发 iteration): when provided, the existing project
        source is seeded so the agent EDITS it per ``change_instruction`` /
        ``change_plan`` instead of regenerating (真实续改); the build ladder + dist
        collection are unchanged so deploy/preview consume the output as before.

        Returns ``{success, degraded, degraded_reason, error, files, dist_files,
        summary, usage, cost_usd, workdir}``. The container always produces a
        previewable ``dist`` (a synthesized notice page in the worst case), so
        ``success`` is True whenever the agent wrote any source; ``degraded`` /
        ``degraded_reason`` report which recovery rung produced the dist. Never
        raises on agent/model failure; raises only on infrastructure errors
        (docker missing, container never exits).
        """
        if not self.is_configured():
            return self._empty("ANTHROPIC_API_KEY not configured")

        figma_block, figma_copies = self._figma_design_block(figma_frames)
        # Keep each upstream doc bounded so the filled prompt stays small enough
        # for the container agent to finish within FE_AGENT_TIMEOUT. The BMAD
        # stage docs are detailed (long); an oversized prompt makes Claude Code
        # time out and fall back to a degraded build. ``documents_digest`` is
        # already capped upstream (``_MAX_DIGEST_CHARS``).
        _cap = 16_000
        edit_mode = bool(base_files)
        fill_vals = dict(
            CONTEXT_LEDGER=context_ledger or "",
            REQUIREMENT=(requirement or "")[:4_000],
            REQUIREMENTS_DOC=(requirements_doc or "")[:_cap],
            DEVELOPMENT_FLOW=(development_flow or "")[:_cap],
            DOCUMENTS=documents_digest or "",
            STYLE_PROMPT=(style_prompt or "")[:_cap],
            UI_BASELINE=(ui_baseline_prompt or "")[:6_000],
            FIGMA_DESIGN=figma_block,
            # Full-stack mode: when a shared API contract is injected the frontend
            # calls the REAL backend (via window.__API_BASE__) instead of using
            # localStorage; empty in standalone mode (backward compatible).
            CONTRACT=(contract_block or "")[:9_000],
        )
        prompt = self._build_prompt(
            fill_vals, edit_mode, base_files or {}, change_instruction, change_plan
        )

        workdir = Path(tempfile.mkdtemp(prefix="fe-agent-"))
        # The container runs as the non-root `node` user (uid 1000) and writes
        # the deliverable to this mounted dir. mkdtemp is 0700 (host user only);
        # on real Linux the container uid couldn't write it (Docker Desktop for
        # Mac is permissive and hides this), so open it up explicitly.
        os.chmod(workdir, 0o777)
        (workdir / "prompt.txt").write_text(prompt, encoding="utf-8")
        # Edit mode: seed the existing project source so the container copies it
        # into the agent workdir (真实续改). Binary-safe; skips pathological files.
        if base_files:
            self._seed_base(workdir / "_base", base_files)
        # The AI repair rung reuses this prompt; the container appends the live
        # build log before invoking claude a second time.
        (workdir / "repair_prompt.txt").write_text(
            self._load_prompt("frontend_project_repair_prompt.txt"), encoding="utf-8"
        )
        # Drop the Figma render images where the container agent can Read them
        # (/out/design/*.png). World-readable so the non-root `node` uid can open
        # them on real Linux (Docker Desktop for Mac is permissive).
        if figma_copies:
            design_dir = workdir / "design"
            design_dir.mkdir(parents=True, exist_ok=True)
            os.chmod(design_dir, 0o777)
            for dest, src in figma_copies:
                try:
                    shutil.copyfile(src, design_dir / dest)
                    os.chmod(design_dir / dest, 0o644)
                except OSError:
                    logger.warning("failed to stage figma render %s", src)
        # Anthropic credential injection: ANTHROPIC_AUTH_TOKEN (+ ANTHROPIC_BASE_URL)
        # for a gateway like zentao.panlaxy.io, else ANTHROPIC_API_KEY. Secrets are
        # passed by NAME (value pulled from `env` below) so they never land in argv.
        cred_flags, cred_env = anthropic_agent_credentials()

        user = container_user()
        cmd = [
            self.docker, "run", "--rm",
            "--user", user,
            *cred_flags,
            # OPENAI_API_KEY passed by NAME (value pulled from `env` below) so it
            # doesn't show up in the `docker run` argv / process list.
            "-e", "OPENAI_API_KEY",
            "-e", f"FE_AGENT_TIMEOUT={self.gen_timeout}",
            "-e", f"FE_AGENT_REPAIR_TIMEOUT={self.repair_timeout}",
            "-e", f"FE_AGENT_NPM_TIMEOUT={self.npm_timeout}",
            "-e", f"FE_AGENT_BUILD_TIMEOUT={self.build_timeout}",
            "-e", f"FE_CODEX_TIMEOUT={self.codex_timeout}",
            "-e", f"FE_GENIMAGE_TIMEOUT={self.genimage_timeout}",
            "-e", f"FE_RUNTIME_TIMEOUT={self.runtime_timeout}",
        ]
        if user != "node":
            # When matching the host UID the image's /home/node is owned by uid
            # 1000 and is not writable. Use /tmp as HOME instead (always 1777).
            cmd += ["-e", "HOME=/tmp"]
        # Non-secret OpenAI image config passthrough, so the in-container genimage
        # call stays aligned with the platform's image provider settings.
        for key in ("OPENAI_BASE_URL", "OPENAI_IMAGE_MODEL", "OPENAI_IMAGE_QUALITY", "OPENAI_IMAGE_SIZE"):
            value = os.getenv(key)
            if value:
                cmd += ["-e", f"{key}={value}"]
        # Optional persistent npm cache across runs (default OFF). Set FE_AGENT_NPM_CACHE
        # to a Docker volume name (or host path) to speed up repeat installs / survive a
        # flaky registry. Empty = unchanged behaviour (fresh per-run cache). Validate with
        # one real generation before relying on it (container user must be able to write
        # the mount). ``--prefer-offline`` (above) makes the warm cache actually used.
        _npm_cache = os.getenv("FE_AGENT_NPM_CACHE", "").strip()
        if _npm_cache:
            cmd += ["-v", f"{_npm_cache}:/npm-cache", "-e", "NPM_CONFIG_CACHE=/npm-cache"]
        cmd += ["-v", f"{host_workdir(workdir)}:/out", self.image, "bash", "-c", _CONTAINER_SCRIPT]

        env = dict(os.environ, **cred_env)
        # OPENAI_API_KEY drives the image-assets skill (Codex). Optional: when
        # unset the build still runs, just with no generated raster assets.
        openai_key = os.getenv("OPENAI_API_KEY")
        if openai_key:
            env["OPENAI_API_KEY"] = openai_key

        # The ladder runs claude up to twice (generate + repair); accumulate the
        # terminal `result` events so cost/usage metering reflects BOTH passes.
        result_events: list[dict] = []
        non_json_stdout: list[str] = []
        proc = subprocess.Popen(
            cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            text=True, bufsize=1, env=env,
        )
        try:
            for line in proc.stdout:
                line = line.strip()
                if not line:
                    continue
                try:
                    event = json.loads(line)
                except json.JSONDecodeError:
                    non_json_stdout.append(line[:500])
                    non_json_stdout = non_json_stdout[-20:]
                    continue  # non-JSON noise on stdout — ignore
                if event.get("type") == "result":
                    result_events.append(event)
                if on_event:
                    try:
                        on_event(event)
                    except Exception:  # noqa: BLE001 - a bad callback must not kill the run
                        logger.exception("on_event callback raised")
                if is_cancelled and is_cancelled():
                    proc.kill()
                    return self._empty("cancelled")
            # total_timeout <= 0 means "wait forever" — pairs with the in-container
            # FE_AGENT_TIMEOUT=0 (uncapped agent). A run is then bounded only by the
            # agent finishing or a cooperative cancel, never by a wall-clock kill.
            proc.wait(timeout=self.total_timeout if self.total_timeout > 0 else None)
        except subprocess.TimeoutExpired:
            proc.kill()
            raise RuntimeError("frontend project agent timed out")
        finally:
            stderr = proc.stderr.read() if proc.stderr else ""
            if stderr:
                logger.info("fe-agent stderr: %s", stderr[:2000])

        docker_exit = proc.returncode
        claude_exit = self._read_exit_code(workdir / "claude_exit")
        npm_install_exit = self._read_exit_code(workdir / "npm_install_exit")
        npm_build_exit = self._read_exit_code(workdir / "npm_build_exit")
        npm_install_log = self._read_text(workdir / "npm_install.log")
        npm_build_log = self._read_text(workdir / "npm_build.log")
        # Which recovery rung produced the dist: "" (clean first build), or one of
        # ai-repair / stub / vite-only / fallback. Anything non-empty is degraded;
        # "fallback" means the dist is a synthesized notice page, not a real build.
        degraded_reason = self._read_text(workdir / "degraded").strip() or None
        files = self._collect(workdir / "project", exclude_top="dist")
        dist_files = self._collect(workdir / "project" / "dist")

        # Runtime smoke (P1-C): parse the headless-browser findings + screenshot
        # (both absent fail-soft when the image bakes no browser → ran:false).
        runtime_check = None
        _rc_raw = self._read_text(workdir / "runtime_check.json")
        if _rc_raw:
            try:
                runtime_check = json.loads(_rc_raw)
            except json.JSONDecodeError:
                runtime_check = None
        runtime_screenshot = None
        _shot = workdir / "runtime" / "screenshot.png"
        if _shot.exists():
            try:
                runtime_screenshot = _shot.read_bytes()
            except OSError:
                runtime_screenshot = None

        # Asset-lane diagnostics: was Codex even present (i.e. was fe-agent
        # rebuilt?), did Claude actually invoke gen-assets, and how many raster
        # assets landed in the source? Lets the host explain a "no assets" run.
        asset_log = self._read_text(workdir / "asset_gen.log")
        asset_lane = {
            "codex_available": bool(self._read_text(workdir / "codex_path").strip()),
            "gen_assets_available": bool(self._read_text(workdir / "gen_assets_path").strip()),
            "openai_key": bool(os.getenv("OPENAI_API_KEY")),
            "calls": sum(1 for ln in asset_log.splitlines() if ln.startswith("invoked:")),
            "assets": sum(1 for key in files if Path(key).suffix.lower() in _BINARY_EXTS),
            "log": asset_log.strip()[:1000],
        }

        # Sum cost/usage across every claude pass (generate + optional repair).
        summary, usage, cost, is_error = "", {}, 0.0, True
        if result_events:
            summary = next(
                (r.get("result") for r in result_events if isinstance(r.get("result"), str)),
                "",
            )
            cost = sum(float(r.get("total_cost_usd") or 0.0) for r in result_events)
            usage = self._merge_usage(result_events)
            is_error = bool(result_events[-1].get("is_error"))

        # The container always synthesizes a previewable dist, so a run is
        # publishable whenever the agent produced source. Hard-fail only when the
        # agent produced nothing at all (config/auth error) -> runtime refunds it.
        success = (docker_exit == 0) and bool(files) and bool(dist_files)
        degraded = success and bool(degraded_reason)
        return {
            "success": success,
            "degraded": degraded,
            "degraded_reason": degraded_reason if degraded else None,
            "error": None if success else self._format_failure(
                docker_exit=docker_exit,
                claude_exit=claude_exit,
                npm_install_exit=npm_install_exit,
                npm_build_exit=npm_build_exit,
                is_error=is_error,
                files=files,
                dist_files=dist_files,
                summary=summary,
                stderr=stderr,
                non_json_stdout=non_json_stdout,
                npm_install_log=npm_install_log,
                npm_build_log=npm_build_log,
            ),
            "files": files,
            "dist_files": dist_files,
            "summary": summary,
            "usage": usage,
            "cost_usd": cost,
            "asset_lane": asset_lane,
            "runtime_check": runtime_check,
            "runtime_screenshot": runtime_screenshot,
            "workdir": str(workdir),
        }

    # --- helpers -------------------------------------------------------------
    @staticmethod
    def _empty(error: str) -> dict:
        return {
            "success": False, "degraded": False, "degraded_reason": None,
            "error": error, "files": {}, "dist_files": {},
            "summary": "", "usage": {}, "cost_usd": 0.0, "asset_lane": {},
            "runtime_check": None, "runtime_screenshot": None, "workdir": None,
        }

    @staticmethod
    def _merge_usage(events: list[dict]) -> dict:
        """Sum integer token counters across every claude `result` event."""
        merged: dict = {}
        for event in events:
            usage = event.get("usage") or {}
            for key, value in usage.items():
                if isinstance(value, (int, float)) and not isinstance(value, bool):
                    merged[key] = merged.get(key, 0) + value
                elif key not in merged:
                    merged[key] = value
        return merged

    @staticmethod
    def _read_exit_code(path: Path) -> int | None:
        try:
            raw = path.read_text(encoding="utf-8").strip()
            return int(raw) if raw else None
        except (OSError, ValueError):
            return None

    @staticmethod
    def _read_text(path: Path) -> str:
        try:
            return path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return ""

    @staticmethod
    def _clip(text: str, limit: int = 1200) -> str:
        text = (text or "").strip()
        return text if len(text) <= limit else f"{text[:limit]}..."

    def _format_failure(
        self,
        *,
        docker_exit: int | None,
        claude_exit: int | None,
        npm_install_exit: int | None,
        npm_build_exit: int | None,
        is_error: bool,
        files: dict,
        dist_files: dict,
        summary: str,
        stderr: str,
        non_json_stdout: list[str],
        npm_install_log: str,
        npm_build_log: str,
    ) -> str:
        reasons: list[str] = []
        # A bind-mount / OCI create failure (DooD) means the agent container never
        # started — surface an actionable hint instead of a cryptic OCI error.
        mount_hint = mount_failure_hint(stderr)
        if mount_hint:
            reasons.append(mount_hint)
        if docker_exit not in (0, None):
            reasons.append(f"container exited with code {docker_exit}")
        if claude_exit not in (0, None):
            reasons.append(f"claude exited with code {claude_exit}")
        if npm_install_exit not in (0, None):
            reasons.append(f"npm install exited with code {npm_install_exit}")
        if npm_build_exit not in (0, None):
            reasons.append(f"npm run build exited with code {npm_build_exit}")
        if npm_build_exit is None:
            reasons.append("npm run build did not run")
        if is_error:
            reasons.append("claude reported an error")
        if not files:
            reasons.append("no source files were published")
        if not dist_files:
            reasons.append("no built dist files were published")

        details: list[str] = []
        if summary:
            details.append(f"summary: {self._clip(summary)}")
        if stderr:
            details.append(f"stderr: {self._clip(stderr)}")
        if non_json_stdout:
            details.append(f"stdout: {self._clip(chr(10).join(non_json_stdout))}")
        if npm_build_log:
            details.append(f"build log: {self._clip(npm_build_log)}")
        elif npm_install_log:
            details.append(f"install log: {self._clip(npm_install_log)}")

        headline = "; ".join(reasons) or "agent did not produce a buildable project"
        return " | ".join([headline, *details])

    def _collect(self, root: Path, exclude_top: Optional[str] = None) -> dict:
        """Return ``{relative_path: bytes}`` for files under ``root``.

        Binary-aware: source/text and generated raster assets are both read as
        raw bytes, so the zip / on-disk dist / GitHub commit keep real image data
        intact (a text-only collector would have corrupted PNGs into empty
        strings). Source text files keep a tight per-file cap; raster assets get a
        larger per-file cap plus a total budget so a runaway image set can't bloat
        the artifact; built bundles (.js/.css/.map/.wasm) get a generous cap so the
        bundler's own large entry chunk is never dropped (which would 404 the
        served preview's entry script and blank the page)."""
        out: dict[str, bytes] = {}
        if not root.exists():
            return out
        asset_budget = _MAX_TOTAL_ASSET_BYTES
        for path in sorted(root.rglob("*")):
            if not path.is_file():
                continue
            rel = path.relative_to(root)
            if exclude_top and rel.parts and rel.parts[0] == exclude_top:
                continue
            suffix = path.suffix.lower()
            is_asset = suffix in _BINARY_EXTS
            if is_asset:
                cap = _MAX_ASSET_BYTES
            elif suffix in _BUNDLE_EXTS:
                cap = _MAX_BUNDLE_BYTES
            else:
                cap = _MAX_TEXT_BYTES
            try:
                size = path.stat().st_size
                if size > cap:
                    logger.warning("skip %s: %d bytes exceeds cap", rel, size)
                    continue
                if is_asset:
                    if size > asset_budget:
                        logger.warning("skip asset %s: total asset budget exhausted", rel)
                        continue
                    asset_budget -= size
                out[str(rel)] = path.read_bytes()
            except OSError:
                continue
        return out


_service_instance: Optional[FrontendProjectService] = None


def get_frontend_project_service() -> FrontendProjectService:
    global _service_instance
    if _service_instance is None:
        _service_instance = FrontendProjectService()
    return _service_instance
